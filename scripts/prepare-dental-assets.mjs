import fs from 'node:fs'
import { createHash } from 'node:crypto'
import { brotliCompressSync, brotliDecompressSync, constants, gzipSync, gunzipSync } from 'node:zlib'

const source = fs.readFileSync('public/models/teeth.glb')
const hash = createHash('sha256').update(source).digest('hex')
const manifest = JSON.parse(fs.readFileSync('public/models/manifest.json', 'utf8'))
if (hash !== manifest.runtime.sha256)
  throw new Error('Actualiza la procedencia y el hash del modelo antes de generar sus versiones comprimidas.')

for (const [suffix, encode, decode] of [
  ['br', (bytes) => brotliCompressSync(bytes, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }), brotliDecompressSync],
  ['gz', (bytes) => gzipSync(bytes, { level: 9 }), gunzipSync],
]) {
  const file = `public/models/teeth.glb.${suffix}`
  let valid = false
  try {
    valid = decode(fs.readFileSync(file)).equals(source)
  } catch {
    /* First build or outdated sidecar. */
  }
  if (!valid) fs.writeFileSync(file, encode(source))
}
const moduleSource = `// Generated by scripts/prepare-dental-assets.mjs; compression does not alter geometry.\nexport const DENTAL_MODEL_HASH = '${hash}'\nexport const DENTAL_MODEL_FILE = 'teeth-${hash.slice(0, 12)}.glb'\nexport const DENTAL_MODEL_URL = \`/models/\${DENTAL_MODEL_FILE}\`\n`
if (!fs.existsSync('src/lib/dental-model.ts') || fs.readFileSync('src/lib/dental-model.ts', 'utf8') !== moduleSource)
  fs.writeFileSync('src/lib/dental-model.ts', moduleSource)
console.log(
  `Modelo verificado: ${source.length} bytes; Brotli ${fs.statSync('public/models/teeth.glb.br').size}; gzip ${fs.statSync('public/models/teeth.glb.gz').size}.`,
)
